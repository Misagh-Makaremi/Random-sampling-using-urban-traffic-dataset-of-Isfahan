############################################################
# 1) بارگذاری داده و آماده‌سازی اندازه‌ها و احتمالات انتخاب
############################################################
# اگر قبلاً انجام نداده‌اید:
# install.packages("dplyr")
library(dplyr)

df <- read.csv("DataT.csv")   # ← مسیر فایل شما
N  <- nrow(df)
n  <- 5

df <- df %>%
  mutate(size = X,
         p    = size / sum(size))  # احتمال انتخاب هر خیابان

############################################################
# 2. نمونه‌گیری PPSWR با دانه تصادفی ثابت
############################################################
set.seed(1234)
index <- sample(1:N, size = n, replace = TRUE, prob = df$p)
samp  <- df[index, ]        # نمونه نهایی
p_s   <- df$p[index]        # بردار احتمال انتخاب‌شده‌ها
y_s   <- samp$Y             # مقادیر y انتخاب‌شده


############################################################
# 3. محاسبه Z_i = y_i / (N * p_i)
############################################################
z <- y_s / (N * p_s)        # طبق فرمول دست‌نویس
ybar_pwr <- mean(z)         # میانگین z_i = ȳ_{PWR}


############################################################
# 4. محاسبه واریانس نمونه‌ای s_z^2 و Var(ȳ_{PWR})
############################################################
s2_z <- var(z)                      # s²_z با (n - 1) در مخرج
var_ybar_pwr <- s2_z / n           # Var(ȳ_{PWR}) = s²_z / n


############################################################
# 5. فاصله اطمینان ۹۵٪ برای ȳ_{PWR}
############################################################
t_crit <- qt(0.975, df = n - 1)
margin <- t_crit * sqrt(var_ybar_pwr)

ci_lower <- ybar_pwr - margin
ci_upper <- ybar_pwr + margin


############################################################
# 6. نمایش نتایج نهایی
############################################################
cat("برآوردگر میانگین (PPSWR): ȳ_PWR      =", ybar_pwr, "\n")
cat("برآورد واریانس ȳ_PWR:               =", var_ybar_pwr, "\n")
cat("انحراف معیار:                         =", sqrt(var_ybar_pwr), "\n")
cat("95% CI برای میانگین جامعه:           [", ci_lower, ",", ci_upper, "]\n")
